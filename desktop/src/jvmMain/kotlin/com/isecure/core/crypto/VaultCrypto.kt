package com.isecure.core.crypto

import java.security.SecureRandom
import java.util.Base64
import javax.crypto.Cipher
import javax.crypto.Mac
import javax.crypto.spec.GCMParameterSpec
import javax.crypto.spec.SecretKeySpec

/**
 * Byte-exact reimplementation of the web vault's crypto (src/crypto.ts),
 * so desktop and Android/web editions read and write the SAME vault
 * envelopes and backups:
 *
 *  - KDF: PBKDF2-HMAC-SHA256, 600,000 iterations by default, 16-byte salt
 *  - Cipher: AES-256-GCM, 12-byte IV, 128-bit tag appended to ciphertext
 *  - Encodings: standard Base64 for salt / iv / ciphertext
 *
 * PBKDF2 is hand-rolled over HmacSHA256 with the password encoded as
 * UTF-8 — WebCrypto encodes the password as UTF-8, while the JCA
 * PBKDF2WithHmacSHA256 provider's char-to-byte conversion has differed
 * across JDKs for non-ASCII passwords. Hand-rolling removes that whole
 * class of doubt; the test vectors (generated by the TypeScript
 * implementation, including a Persian master password) prove parity.
 */
object VaultCrypto {
    const val DEFAULT_KDF_ITERATIONS = 600_000
    const val MIN_KDF_ITERATIONS = 1_000
    const val MAX_KDF_ITERATIONS = 10_000_000

    private const val SALT_BYTES = 16
    private const val IV_BYTES = 12
    private const val KEY_BYTES = 32
    private const val GCM_TAG_BITS = 128

    private val random = SecureRandom()

    fun generateSalt(): ByteArray = ByteArray(SALT_BYTES).also { random.nextBytes(it) }

    fun generateIv(): ByteArray = ByteArray(IV_BYTES).also { random.nextBytes(it) }

    fun pbkdf2HmacSha256(
        password: ByteArray,
        salt: ByteArray,
        iterations: Int,
        keyLengthBytes: Int = KEY_BYTES,
    ): ByteArray {
        require(iterations in MIN_KDF_ITERATIONS..MAX_KDF_ITERATIONS) {
            "PBKDF2 iterations out of accepted range: $iterations"
        }
        val mac = Mac.getInstance("HmacSHA256")
        mac.init(SecretKeySpec(password, "HmacSHA256"))
        val hashLen = mac.macLength
        val derived = ByteArray(keyLengthBytes)
        var produced = 0
        var blockIndex = 1
        while (produced < keyLengthBytes) {
            // U1 = PRF(password, salt || INT_32_BE(blockIndex))
            mac.update(salt)
            var u = mac.doFinal(
                byteArrayOf(
                    (blockIndex ushr 24).toByte(),
                    (blockIndex ushr 16).toByte(),
                    (blockIndex ushr 8).toByte(),
                    blockIndex.toByte(),
                ),
            )
            val t = u.copyOf()
            repeat(iterations - 1) {
                u = mac.doFinal(u)
                for (j in t.indices) {
                    t[j] = (t[j].toInt() xor u[j].toInt()).toByte()
                }
            }
            val take = minOf(hashLen, keyLengthBytes - produced)
            System.arraycopy(t, 0, derived, produced, take)
            produced += take
            blockIndex++
        }
        return derived
    }

    fun deriveKey(masterSecret: String, salt: ByteArray, iterations: Int): ByteArray =
        pbkdf2HmacSha256(masterSecret.toByteArray(Charsets.UTF_8), salt, iterations)

    fun aesGcmEncrypt(key: ByteArray, iv: ByteArray, plaintext: ByteArray): ByteArray {
        val cipher = Cipher.getInstance("AES/GCM/NoPadding")
        cipher.init(
            Cipher.ENCRYPT_MODE,
            SecretKeySpec(key, "AES"),
            GCMParameterSpec(GCM_TAG_BITS, iv),
        )
        return cipher.doFinal(plaintext)
    }

    fun aesGcmDecrypt(key: ByteArray, iv: ByteArray, ciphertext: ByteArray): ByteArray {
        val cipher = Cipher.getInstance("AES/GCM/NoPadding")
        cipher.init(
            Cipher.DECRYPT_MODE,
            SecretKeySpec(key, "AES"),
            GCMParameterSpec(GCM_TAG_BITS, iv),
        )
        return cipher.doFinal(ciphertext)
    }

    fun bytesToBase64(bytes: ByteArray): String =
        Base64.getEncoder().encodeToString(bytes)

    fun base64ToBytes(b64: String): ByteArray =
        Base64.getDecoder().decode(b64)
}
