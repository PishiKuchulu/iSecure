@Composable
fun GeneratorTab(state: VaultAppState) {
    val strings = state.strings
    var options by remember {
        mutableStateOf(PasswordGenerator.Options())
    }
    var generated by remember { mutableStateOf("") }

    LaunchedEffect(options) {
        generated = PasswordGenerator.generate(state.random, options) ?: ""
    }

    val strength = VaultLogic.passwordStrength(generated)
    val strengthLabel = when (strength) {
        VaultLogic.PasswordStrength.WEAK -> strings.genStrengthWeak
        VaultLogic.PasswordStrength.FAIR -> strings.genStrengthFair
        VaultLogic.PasswordStrength.GOOD -> strings.genStrengthGood
        VaultLogic.PasswordStrength.EXCELLENT -> strings.genStrengthExcellent
    }

    Column(
        Modifier.fillMaxSize().padding(16.dp),
        verticalArrangement = Arrangement.spacedBy(12.dp),
    ) {
        Card(Modifier.fillMaxWidth()) {
            Column(Modifier.padding(16.dp)) {
                Text(
                    generated,
                    style = MaterialTheme.typography.titleMedium,
                )
                Spacer(Modifier.height(8.dp))
                Text(
                    "${strings.genStrength}: $strengthLabel · " +
                        "${strings.genEntropy}: ${VaultLogic.calculateEntropy(generated)}",
                    style = MaterialTheme.typography.bodySmall,
                    color = MaterialTheme.colorScheme.onSurfaceVariant,
                )
                Spacer(Modifier.height(8.dp))
                Row(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
                    Button(onClick = {
                        generated = PasswordGenerator.generate(
                            state.random, options,
                        ) ?: ""
                    }) {
                        Text(strings.generator)
                    }
                    TextButton(
                        onClick = { if (generated.isNotEmpty()) state.copySecret(generated) },
                    ) {
                        Text(strings.copy)
                    }
                }
            }
        }
        Text("${strings.genLength}: ${options.length}")
        Slider(
            value = options.length.toFloat(),
            onValueChange = { options = options.copy(length = it.toInt()) },
            valueRange = 8f..64f,
            steps = 55,
        )
        OptionSwitch(strings.genLowercase, options.includeLower) {
            options = options.copy(includeLower = it)
        }
        OptionSwitch(strings.genUppercase, options.includeUpper) {
            options = options.copy(includeUpper = it)
        }
        OptionSwitch(strings.genNumbers, options.includeNumbers) {
            options = options.copy(includeNumbers = it)
        }
        OptionSwitch(strings.genSymbols, options.includeSymbols) {
            options = options.copy(includeSymbols = it)
        }
        OptionSwitch(strings.genExcludeSimilar, options.excludeSimilar) {
            options = options.copy(excludeSimilar = it)
        }
    }
}

@Composable
private fun OptionSwitch(
    label: String,
    checked: Boolean,
    onCheckedChange: (Boolean) -> Unit,
) {
    Row(verticalAlignment = Alignment.CenterVertically) {
        Text(label, Modifier.weight(1f))
        Switch(checked = checked, onCheckedChange = onCheckedChange)
    }
}

@Composable
fun AuditTab(state: VaultAppState) {
    val strings = state.strings
    val result = remember(state.entries) {
        VaultLogic.auditVault(state.entries, Clock.System.now())
    }
    val byId = state.entries.associateBy { it.id }

    LazyColumn(
        Modifier.fillMaxSize().padding(16.dp),
        verticalArrangement = Arrangement.spacedBy(12.dp),
    ) {
        item {
            Card(Modifier.fillMaxWidth()) {
                Column(Modifier.padding(16.dp)) {
                    Text(
                        "${strings.securityScore}: ${result.score}",
                        style = MaterialTheme.typography.headlineSmall,
                    )
                    Text(
                        strings.auditScoreDesc,
                        style = MaterialTheme.typography.bodySmall,
                        color = MaterialTheme.colorScheme.onSurfaceVariant,
                    )
                }
            }
        }
        if (result.weakIds.isEmpty() && result.reusedIds.isEmpty() &&
            result.oldIds.isEmpty()
        ) {
            item { Text(strings.auditSecureDesc) }
        }
        if (result.weakIds.isNotEmpty()) {
            item {
                Text(
                    "${strings.weak} (${result.weakIds.size})",
                    style = MaterialTheme.typography.titleMedium,
                )
                Text(strings.auditWeakDesc, style = MaterialTheme.typography.bodySmall)
            }
            items(result.weakIds) { id ->
                Text(byId[id]?.title ?: id, Modifier.padding(start = 8.dp))
            }
        }
        if (result.reusedIds.isNotEmpty()) {
            item {
                Text(
                    "${strings.reused} (${result.reusedIds.size})",
                    style = MaterialTheme.typography.titleMedium,
                )
                Text(strings.auditReuseDesc, style = MaterialTheme.typography.bodySmall)
            }
            items(result.reusedIds) { id ->
                Text(byId[id]?.title ?: id, Modifier.padding(start = 8.dp))
            }
        }
        if (result.oldIds.isNotEmpty()) {
            item {
                Text(
                    "${strings.old} (${result.oldIds.size})",
                    style = MaterialTheme.typography.titleMedium,
                )
                Text(strings.auditOldDesc, style = MaterialTheme.typography.bodySmall)
            }
            items(result.oldIds) { id ->
                Text(byId[id]?.title ?: id, Modifier.padding(start = 8.dp))
            }
        }
    }
}

@Composable
fun TrashTab(state: VaultAppState) {
    val strings = state.strings
    val trashed = state.entries.filter { it.isTrash }
    var confirmPurge by remember { mutableStateOf(false) }
    var confirmDeleteId by remember { mutableStateOf<String?>(null) }

    Column(Modifier.fillMaxSize().padding(16.dp)) {
        if (trashed.isNotEmpty()) {
            Button(onClick = { confirmPurge = true }) {
                Text(strings.permanentlyDelete + " — " + strings.trashBin)
            }
            Spacer(Modifier.height(12.dp))
        }
        if (trashed.isEmpty()) {
            Text(
                strings.noEntries,
                color = MaterialTheme.colorScheme.onSurfaceVariant,
            )
        } else {
            LazyColumn(verticalArrangement = Arrangement.spacedBy(8.dp)) {
                items(trashed, key = { it.id }) { entry ->
                    Card(Modifier.fillMaxWidth()) {
                        Row(
                            Modifier.padding(12.dp),
                            verticalAlignment = Alignment.CenterVertically,
                        ) {
                            Column(Modifier.weight(1f)) {
                                Text(entry.title, style = MaterialTheme.typography.titleMedium)
                                Text(
                                    entry.deletedAt?.take(10) ?: "",
                                    style = MaterialTheme.typography.bodySmall,
                                    color = MaterialTheme.colorScheme.onSurfaceVariant,
                                )
                            }
                            TextButton(onClick = { state.restoreEntry(entry.id) }) {
                                Text(strings.restore)
                            }
                            TextButton(onClick = { confirmDeleteId = entry.id }) {
                                Text(
                                    strings.permanentlyDelete,
                                    color = MaterialTheme.colorScheme.error,
                                )
                            }
                        }
                    }
                }
            }
        }
    }

    if (confirmPurge) {
        AlertDialog(
            onDismissRequest = { confirmPurge = false },
            title = { Text(strings.trashBin) },
            text = { Text(strings.permanentlyDelete) },
            confirmButton = {
                TextButton(onClick = {
                    state.purgeTrash()
                    confirmPurge = false
                }) {
                    Text(strings.permanentlyDelete, color = MaterialTheme.colorScheme.error)
                }
            },
            dismissButton = {
                TextButton(onClick = { confirmPurge = false }) {
                    Text(strings.cancel)
                }
            },
        )
    }
    confirmDeleteId?.let { id ->
        AlertDialog(
            onDismissRequest = { confirmDeleteId = null },
            title = { Text(strings.permanentlyDelete) },
            text = { Text(state.entries.firstOrNull { it.id == id }?.title ?: "") },
            confirmButton = {
                TextButton(onClick = {
                    state.deleteForever(id)
                    confirmDeleteId = null
                }) {
                    Text(strings.permanentlyDelete, color = MaterialTheme.colorScheme.error)
                }
            },
            dismissButton = {
                TextButton(onClick = { confirmDeleteId = null }) {
                    Text(strings.cancel)
                }
            },
        )
    }
}

@Composable
fun SettingsTab(state: VaultAppState) {
    val strings = state.strings
    val settings = state.settings
    val scope = rememberCoroutineScope()
    var importSecret by remember { mutableStateOf("") }
    var showImport by remember { mutableStateOf(false) }
    var importError by remember { mutableStateOf(false) }
    var newCategory by remember { mutableStateOf("") }

    LazyColumn(
        Modifier.fillMaxSize().padding(16.dp),
        verticalArrangement = Arrangement.spacedBy(16.dp),
    ) {
        item {
            Text(strings.theme, style = MaterialTheme.typography.titleMedium)
            Spacer(Modifier.height(4.dp))
            Row(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
                listOf(
                    "light" to strings.themeLight,
                    "dark" to strings.themeDark,
                    "amoled" to strings.themeAmoled,
                    "system" to strings.themeSystem,
                ).forEach { (value, label) ->
                    TextButton(
                        onClick = { state.updateSettings(settings.copy(theme = value)) },
                    ) {
                        Text(
                            (if (settings.theme == value) "● " else "○ ") + label,
                        )
                    }
                }
            }
        }
        item {
            Text(strings.settingsTitle, style = MaterialTheme.typography.titleMedium)
            Spacer(Modifier.height(4.dp))
            Column {
                SUPPORTED_LOCALES.forEach { code ->
                    TextButton(
                        onClick = {
                            state.updateSettings(settings.copy(language = code))
                        },
                    ) {
                        Text(
                            (if (settings.language == code) "● " else "○ ") +
                                (LANGUAGE_NAMES[code] ?: code),
                        )
                    }
                }
            }
        }
        item {
            Text(strings.autoLock, style = MaterialTheme.typography.titleMedium)
            Spacer(Modifier.height(4.dp))
            Row(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
                listOf(0, 1, 5, 15, 30).forEach { minutes ->
                    TextButton(
                        onClick = {
                            state.updateSettings(settings.copy(autoLockMinutes = minutes))
                        },
                    ) {
                        Text(
                            (if (settings.autoLockMinutes == minutes) "● " else "○ ") +
                                if (minutes == 0) strings.autoLockDisabled else "$minutes",
                        )
                    }
                }
            }
        }
        item {
            Text(strings.clipboardAuto, style = MaterialTheme.typography.titleMedium)
            Text(
                strings.clipboardAutoDesc,
                style = MaterialTheme.typography.bodySmall,
                color = MaterialTheme.colorScheme.onSurfaceVariant,
            )
            Spacer(Modifier.height(4.dp))
            Row(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
                listOf(0, 15, 30, 60).forEach { seconds ->
                    TextButton(
                        onClick = {
                            state.updateSettings(
                                settings.copy(clipboardClearSeconds = seconds),
                            )
                        },
                    ) {
                        Text(
                            (if (settings.clipboardClearSeconds == seconds) "● " else "○ ") +
                                if (seconds == 0) strings.clipDisabled else "$seconds",
                        )
                    }
                }
            }
        }
        item {
            Text(strings.category, style = MaterialTheme.typography.titleMedium)
            Spacer(Modifier.height(4.dp))
            Row(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
                OutlinedTextField(
                    value = newCategory,
                    onValueChange = { newCategory = it },
                    singleLine = true,
                    modifier = Modifier.weight(1f),
                )
                Button(onClick = {
                    state.addCategory(newCategory)
                    newCategory = ""
                }) {
                    Text(strings.addField)
                }
            }
            if (state.customCategories.isNotEmpty()) {
                Text(
                    state.customCategories.joinToString(", "),
                    style = MaterialTheme.typography.bodySmall,
                    color = MaterialTheme.colorScheme.onSurfaceVariant,
                )
            }
        }
        if (state.fileExchangeAvailable) {
            item {
                Text(strings.cloudBackupTitle, style = MaterialTheme.typography.titleMedium)
                Spacer(Modifier.height(4.dp))
                Row(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
                    Button(onClick = {
                        val json = state.exportEnvelopeJson() ?: return@Button
                        scope.launch {
                            withContext(Dispatchers.IO) {
                                state.saveBackupFile(json)
                            }
                        }
                    }) {
                        Text(strings.cloudBackupTitle)
                    }
                    TextButton(onClick = { showImport = true }) {
                        Text(strings.restore)
                    }
                }
            }
        }
        item {
            Text(strings.aboutTitle, style = MaterialTheme.typography.titleMedium)
            Spacer(Modifier.height(4.dp))
            Text(strings.aboutDesc, style = MaterialTheme.typography.bodyMedium)
            Text(
                "Zero-Knowledge Password Manager",
                style = MaterialTheme.typography.bodySmall,
                color = MaterialTheme.colorScheme.onSurfaceVariant,
            )
        }
    }

    if (showImport) {
        AlertDialog(
            onDismissRequest = { showImport = false; importError = false },
            title = { Text(strings.restore) },
            text = {
                Column {
                    OutlinedTextField(
                        value = importSecret,
                        onValueChange = { importSecret = it; importError = false },
                        label = { Text(strings.masterPassword) },
                        singleLine = true,
                        visualTransformation = PasswordVisualTransformation(),
                        modifier = Modifier.fillMaxWidth(),
                    )
                    if (importError) {
                        Text(
                            strings.wrongPassword,
                            color = MaterialTheme.colorScheme.error,
                            style = MaterialTheme.typography.bodySmall,
                        )
                    }
                }
            },
            confirmButton = {
                Button(onClick = {
                    scope.launch {
                        val text = withContext(Dispatchers.IO) {
                            state.openBackupFile()
                        } ?: return@launch
                        val ok = state.importBackup(text, importSecret)
                        if (ok) {
                            showImport = false
                            importSecret = ""
                        } else {
                            importError = true
                        }
                    }
                }) {
                    Text(strings.restore)
                }
            },
            dismissButton = {
                TextButton(onClick = { showImport = false }) {
                    Text(strings.cancel)
                }
            },
        )
    }
}
