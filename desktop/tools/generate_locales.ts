/**
 * Generates the Kotlin locale tables for the KMP app from the SINGLE
 * source of truth — src/locales.ts of the web app — so the desktop /
 * Android-native editions can never drift from the shipped strings.
 *
 * Run from the project root:
 *   bun run desktop/tools/generate_locales.ts
 *
 * Outputs (both marked generated, do not hand-edit):
 *   desktop/src/commonMain/kotlin/com/isecure/core/i18n/LocalesData.kt
 *   desktop/src/commonMain/kotlin/com/isecure/core/i18n/Strings.kt
 */
import { localesMap } from '../../src/locales';

type LocaleMap = Record<string, string | boolean>;

const codes = Object.keys(localesMap);
const en = localesMap.en as unknown as LocaleMap;
const keys = Object.keys(en).filter((k) => k !== 'isRTL');
for (const key of keys) {
  if (!/^[a-zA-Z][a-zA-Z0-9]*$/.test(key)) {
    throw new Error(`Locale key is not a valid Kotlin identifier: ${key}`);
  }
}

/** Escape one string as a Kotlin double-quoted literal. */
function kt(value: string): string {
  let out = '"';
  for (const ch of value) {
    const code = ch.codePointAt(0) ?? 0;
    if (ch === '"') out += '\\"';
    else if (ch === '\\') out += '\\\\';
    else if (ch === '$') out += '\\$';
    else if (ch === '\n') out += '\\n';
    else if (ch === '\r') out += '\\r';
    else if (ch === '\t') out += '\\t';
    else if (code < 0x20) out += `\\u${code.toString(16).padStart(4, '0')}`;
    else out += ch;
  }
  return out + '"';
}

const rtlCodes = codes.filter(
  (c) => (localesMap[c as keyof typeof localesMap] as unknown as LocaleMap).isRTL === true,
);

let data = `package com.isecure.core.i18n

// GENERATED by desktop/tools/generate_locales.ts from src/locales.ts —
// do not hand-edit. Regenerate after any locale change in the web app.

internal val RTL_LOCALES: Set<String> = setOf(${rtlCodes.map((c) => kt(c)).join(', ')})

internal val LOCALE_STRINGS: Map<String, Map<String, String>> = mapOf(
`;
for (const code of codes) {
  const map = localesMap[code as keyof typeof localesMap] as unknown as LocaleMap;
  data += `    ${kt(code)} to mapOf(\n`;
  for (const key of keys) {
    const value = map[key];
    if (typeof value !== 'string') {
      throw new Error(`Locale ${code} is missing string key ${key}`);
    }
    data += `        ${kt(key)} to ${kt(value)},\n`;
  }
  data += '    ),\n';
}
data += ')\n';

let strings = `package com.isecure.core.i18n

// GENERATED by desktop/tools/generate_locales.ts from src/locales.ts —
// do not hand-edit. Regenerate after any locale change in the web app.

/**
 * Typed access to the locale strings, mirroring the TS Strings shape.
 * Lookups fall back to English, then to the key itself.
 */
class Strings(
    val localeCode: String,
    private val values: Map<String, String>,
    private val fallback: Map<String, String>,
) {
    val isRTL: Boolean get() = localeCode in RTL_LOCALES

    operator fun get(key: String): String = values[key] ?: fallback[key] ?: key

`;
for (const key of keys) {
  strings += `    val ${key}: String get() = get("${key}")\n`;
}
strings += `}

fun stringsFor(code: String): Strings {
    val en = LOCALE_STRINGS.getValue("en")
    val map = LOCALE_STRINGS[code] ?: en
    return Strings(if (LOCALE_STRINGS.containsKey(code)) code else "en", map, en)
}

val SUPPORTED_LOCALES: List<String> = listOf(${codes.map((c) => kt(c)).join(', ')})
`;

const outDir = new URL('../src/commonMain/kotlin/com/isecure/core/i18n/', import.meta.url)
  .pathname;
await Bun.write(`${outDir}LocalesData.kt`, data);
await Bun.write(`${outDir}Strings.kt`, strings);
console.log(`generated ${codes.length} locales x ${keys.length} keys`);
